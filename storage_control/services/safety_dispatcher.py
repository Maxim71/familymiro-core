def send_safety_briefing_notification(safety_pass, confirm_url: str) -> str:
    """Отправляет карточку инструктажа и ссылку подтверждения в Telegram-бот."""
    token = os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
    chat_id = (safety_pass.contact_channel or os.getenv("TELEGRAM_CHAT_ID", "")).strip()
    text_body = safety_pass.briefing_text or HAZARD_INSTRUCTIONS.get(safety_pass.hazard_signal, HAZARD_INSTRUCTIONS["NONE"])

    msg = (
        f"🦺 <b>СИГНАЛ ОТ И ТБ — ЦЕЛЕВОЙ ИНСТРУКТАЖ</b>\n"
        f"Раздел: <b>{safety_pass.discipline}</b> | Подрядчик: <b>{safety_pass.contractor_name}</b>\n"
        f"Бригадир: <b>{safety_pass.brigadier_name}</b> ({safety_pass.workers_count} чел.)\n"
        f"Опасный фактор: <b>{safety_pass.get_hazard_signal_display()}</b>\n\n"
        f"{text_body}\n\n"
        f"👉 Подтвердить прочтение и прикрепить фото СИЗ:\n{confirm_url}"
    )

    if token and chat_id and chat_id.lstrip("-").isdigit():
        try:
            requests.post(
                f"https://telegram.org{token}/sendMessage",
                json={"chat_id": chat_id, "text": msg, "parse_mode": "HTML"},
                timeout=5,
            )
            return "Уведомление отправлено в Telegram!"
        except Exception:
            pass
    return f"Ссылка на подпись в журнале ТБ сформирована: {confirm_url}"
