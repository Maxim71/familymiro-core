def load_penetration_limits(section_id, size_dimensions):
    """
    🪐 FAMILYMIRA OMNI-PENETRATION LIMITER — SECTION 1.2
    Автоматический балансировщик спроса кабельных проходок и отверстий.
    Считает лимиты прохождений в мм на основе кодов разделов проекта.
    """
    # Вытаскиваем или создаем чистую базу проходок
    penetration_log_path = "history_log.json"
    
    # Расчет проектного лимита диаметров отверстий по ГОСТу
    # Для тяжелой слаботочки и СКС лимит больше, для автоматики - точечный
    if "СКС" in section_id or "СКК" in section_id:
        max_allowed_diameter_mm = 500.0  # Максимальный спрос прохождений по смете
    else:
        max_allowed_diameter_mm = 200.0  # Точечный лимит прохода воздуховодов/труб

    # Извлекаем из строки габаритов цифры (например из "D=150" или "400х200" вытащит число)
    try:
        cleaned_size = ''.join(c for c in str(size_dimensions) if c.isdigit() or c == '.')
        requested_size = float(cleaned_size) if cleaned_size else 150.0
    except:
        requested_size = 150.0

    return {
        "max_project_limit_mm": max_allowed_diameter_mm,
        "requested_size_mm": requested_size,
        "is_within_limits": requested_size <= max_allowed_diameter_mm
    }



