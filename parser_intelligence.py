def ezhik_parse_filename(filename):
    """
    Строительный интеллект Ёжика: анализирует имя файла или строки спецификации,
    выделяет шифр тома, порядковый номер и сопоставляет с Базой Знаний.
    """
    # Регулярное выражение для поиска шифров (например: "01-ГП", "11-КЖ0.3", "64-ЭОМ.ЦОД")
    pattern = r'(?P<index>\d+)-(?P<code>[A-ZА-Я]+(?:\.[A-ZА-Я]+)?)(?P<sub_index>\d+(?:\.\d+)*)?'
    
    match = re.search(pattern, filename)
    if not match:
        return {
            "status": "unknown",
            "message": "Ёжик не смог распознать стандартный строительный шифр."
        }
    
    data = match.groupdict()
    code = data["code"]
    
    # Ищем расшифровку в нашей базе знаний
    description = CONSTRUCTION_KNOWLEDGE_BASE.get(code, "Неизвестный ИТР-раздел (требуется обучение)")
    
    return {
        "status": "success",
        "parsed_data": {
            "index": data["index"],
            "cipher": code,
            "sub_index": data["sub_index"] if data["sub_index"] else "1",
            "name": description
        },
        "target_module": "Снабжение/Склад" if code in ["ЭОМ", "ВК", "КМ"] else "Проектирование/ИТР"
    }

# Тест-драйв интеллекта (обучающий пример)
if __name__ == "__main__":
    test_files = [
        "11-КЖ0.3 (Вертикальные конструкции).pdf",
        "64-ЭОМ.ЦОД (Силовое электрооборудование).dwg",
        "32-ВК1 (Внутренние системы).rar"
    ]
    print("=== ТЕСТИРОВАНИЕ СТРОИТЕЛЬНОГО ИНТЕЛЛЕКТА ЁЖИКА ===")
    for f in test_files:
        result = ezhik_parse_filename(f)
        print(f"Файл: {f} -> Распознано Ёжиком: {result['parsed_data']}")
