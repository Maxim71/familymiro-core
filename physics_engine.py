from PIL import Image, ImageDraw

def render_pdf_production_map(axis_name):
    """Модернизированный Pillow-движок с сочным, контрастным ИТР-подсветом слоев"""
    # Вертикальный Android-кадр (720x450 для идеального размещения под матрицей)
    img = Image.new("RGBA", (720, 450), (13, 17, 23, 255))
    draw = ImageDraw.Draw(img)
    
    # Тонкая неоновая рамка NASA-панели
    draw.rectangle(((10, 10), (710, 440)), outline=(88, 166, 255, 180), width=2)
    
    axis_upper = axis_name.upper()
    if "А-Б" in axis_upper or "1-2" in axis_upper:
        # 1. Базовый контур стены из чертежа АР1.5 (Делаем рамку ярче)
        draw.rectangle(((40, 80), (680, 380)), outline=(88, 166, 255, 255), width=2)
        
        # 🟢 СВЕРХЯРКИЙ НЕОНОВЫЙ ПОДСВЕТ ВЫРАБОТКИ (Шпатлевка Limonapro + Грунт / Выполнено 100%)
        # Увеличиваем плотность альфа-канала с 35 до 90 и делаем жирный бирюзовый контур!
        draw.rectangle(((42, 82), (360, 378)), fill=(0, 255, 204, 90), outline=(0, 255, 204, 255), width=3)
        draw.text((50, 100), "🟢 СДАННЫЕ ОБЪЕМЫ (100%):\nШпатлевка Limonapro\nГрунтовка Knauf\nПлощадь: 1,240.50 м²", fill=(255, 255, 255, 255))
        
        # 🟡 СВЕРХЯРКИЙ СИГНАЛЬНЫЙ ПОДСВЕТ ЗОНЫ М-15 (Краска Lakra в 2 слоя / В работе)
        draw.rectangle(((361, 82), (678, 378)), fill=(255, 153, 0, 90), outline=(255, 153, 0, 255), width=3)
        draw.text((380, 100), "🟡 В РАБОТЕ ПО М-15:\nФинишная окраска\nЛатексная краска Lakra\nЛимит: 100 кг (20 ведер)", fill=(255, 255, 255, 255))
        
        # 🚪 Дверной проем ПР-02 и дверь ДП-21-10 EI60 (Кристальный бирюзовый неон)
        draw.rectangle(((260, 160), (460, 378)), fill=(13, 17, 23, 255), outline=(0, 242, 254, 255), width=4)
        draw.text((285, 250), "🚪 ДВЕРЬ ПР-02\n ДП-21-10", fill=(0, 242, 254, 255))
        
        # 🚨 ЖЕСТКОЕ ВЫДЕЛЕНИЕ СКРЫТОГО ЭЛЕМЕНТА УСИЛЕНИЯ (Швеллер [ №10 / Красный Марс)
        # Делаем швеллер максимально широким и контрастным!
        draw.rectangle(((235, 155), (258, 380)), fill=(255, 51, 51, 255), outline=(255, 255, 255, 255), width=1)
        draw.rectangle(((462, 155), (485, 380)), fill=(255, 51, 51, 255), outline=(255, 255, 255, 255), width=1)
        draw.text((245, 120), "🚨 СКРЫТЫЙ ШВЕЛЛЕР [ №10", fill=(255, 51, 51, 255))
    else:
        draw.text((180, 200), f"ВЕКТОРНЫЙ СЛОЙ ОСИ {axis_upper}\nУЗЛЫ ОТСУТСТВУЮТ", fill=(160, 160, 160, 255))
        
    return img

def render_pin_card(title, data_lines, status_color):
    """Генератор красивых ИТР ПИН-карточек строго 200x330 пикселей по ГОСТу Создателя"""
    img = Image.new("RGBA", (200, 330), (22, 27, 34, 255))
    draw = ImageDraw.Draw(img)
    draw.rectangle(((2, 2), (198, 328)), outline=status_color, width=2)
    draw.text((12, 15), title.upper(), fill=status_color)
    draw.line(((12, 38), (188, 38)), fill=(88, 166, 255, 60), width=1)
    y_pos = 50
    for line in data_lines:
        draw.text((12, y_pos), line, fill=(201, 209, 217, 255))
        y_pos += 35
    draw.line(((12, 285), (188, 285)), fill=(88, 166, 255, 60), width=1)
    draw.text((12, 298), "🔒 СЛОЙ СИНДИКАТА", fill=(88, 166, 255, 150))
    return img
