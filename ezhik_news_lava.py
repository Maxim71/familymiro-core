import json
import random

def generate_weekly_itr_report(responsible_accepted):
    print("\n" + "="*80)
    print("🦔 [ИТР-ОТЧЕТ ЕЖИКА] ЕЖЕНЕДЕЛЬНЫЙ АНАЛИЗ СОСТОЯНИЯ ОБЪЕКТА ХОЛДИНГА (ПОРТ 3500)")
    print("="*80)
    
    # 1. Каскад анализа прочности и ухода за бетоном по осям
    print("\n[🧱 КОНТРОЛЬ БЕТОНИРОВАНИЯ И ОСЕЙ]:")
    if responsible_accepted:
        print("   ● [🟢 СТАТУС]: Ответственность принята Начальником Участка.")
        print("   ● [📜 ПРЕДПИСАНИЕ ЕЖИКА]: Начать технологический уход за бетоном (полив, укрытие).")
        print("   ● [📐 ОСИ]: Дальнейшее проектное движение заблокировано до набора 70% прочности.")
    else:
        print("   ● [🚨 КРИТИЧЕСКИЙ СТОПОР]: Отклонение осей не устранено! Ответственный не назначен.")
        print("   ● [🔒 LAVA API]: Финансовые выплаты СУБД заблокированы. Доля 4% на холде.")

    # 2. Автоматическая сверка табеля людей и состава ИТР
    print("\n[📊 СВЕРКА ТАБЕЛЯ И СОТРУДНИКОВ СИЛЫ]:")
    tabel_data = {
        "workers_fact": 12,
        "workers_plan": 15,
        "itr_active": ["Прораб_Максим", "Геодезист_Алексей"],
        "current_nodes": "Заливка ростверка осей 1-4, вязка арматуры Блок Б"
    }
    
    labor_deficit = tabel_data["workers_plan"] - tabel_data["workers_fact"]
    print(f"   ● [👷 Рабочие на объекте]: Факт: {tabel_data['workers_fact']} чел. | План: {tabel_data['workers_plan']} чел.")
    if labor_deficit > 0:
        print(f"   ● [⚠️ ВНИМАНИЕ]: Дефицит рабочей силы: {labor_deficit} чел. на инженерных узлах!")
    print(f"   ● [🛠️ Активные Узлы ИТР]: {tabel_data['current_nodes']}")
    print(f"   ● [👤 Состав ИТР на постах]: {', '.join(tabel_data['itr_active'])}")
    
    # 3. Финансовая фиксация
    print("\n[💳 АВТОМАТИЗАЦИЯ ВЫПЛАТ LAVA API]:")
    print("   ● [🔒 Безопасность]: Авторские права Создателя и 4% пассивного кофе-капитала запечатаны.")
    print("="*80 + "\n")

if __name__ == "__main__":
    # Тестируем сценарий: Начальник участка принял ответственность и Ежик выдал уход за бетоном
    generate_weekly_itr_report(responsible_accepted=True)
